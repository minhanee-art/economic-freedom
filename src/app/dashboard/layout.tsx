export default function DashboardLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const pathname = usePathname();
  const router = useRouter();

  const handleLogout = async () => {
    const supabase = createClient();
    await supabase.auth.signOut();
    router.push("/login");
  };

  return (
    <div className="flex flex-col min-h-full pb-16 md:pb-0">
      {/* PC 헤더 */}
      <header className="bg-dark-header text-white">
        <div className="mx-auto max-w-[860px] px-4 flex h-14 items-center justify-between">
          <Link href="/dashboard" className="font-bold text-lg">
            Pension Manager
          </Link>
          <button
            onClick={handleLogout}
            className="text-sm text-zinc-400 hover:text-white transition-colors"
          >
            로그아웃
          </button>
        </div>
      </header>

      {/* PC 탭 네비게이션 (모바일에서 숨김) */}
      <nav className="hidden md:block bg-dark-header border-t border-white/10">
        <div className="mx-auto max-w-[860px] px-4 flex gap-1">
          {navItems.map((item) => {
            const isActive =
              item.href === "/dashboard"
                ? pathname === "/dashboard"
                : pathname.startsWith(item.href);

            return (
              <Link
                key={item.href}
                href={item.href}
                className={cn(
                  "px-3 py-2.5 text-sm font-medium whitespace-nowrap border-b-2 transition-colors",
                  isActive
                    ? "border-indigo-500 text-white"
                    : "border-transparent text-zinc-400 hover:text-white"
                )}
              >
                {item.label}
              </Link>
            );
          })}
        </div>
      </nav>

      {/* 콘텐츠 */}
      <main className="flex-1 bg-zinc-50 dark:bg-zinc-950">
        <div className="mx-auto max-w-[860px] px-4 py-5">
          {children}
        </div>
      </main>

      {/* 모바일 하단 네비게이션 (PC에서 숨김) */}
      <nav className="fixed bottom-0 left-0 right-0 md:hidden bg-white dark:bg-zinc-900 border-t border-zinc-200 dark:border-zinc-800 z-50">
        <div className="flex justify-around items-center h-16 max-w-[860px] mx-auto">
          {navItems.map((item) => {
            const isActive =
              item.href === "/dashboard"
                ? pathname === "/dashboard"
                : pathname.startsWith(item.href);

            return (
              <Link
                key={item.href}
                href={item.href}
                className={cn(
                  "flex flex-col items-center gap-0.5 px-2 py-1 text-[10px] font-medium transition-colors",
                  isActive
                    ? "text-indigo-500"
                    : "text-zinc-400 hover:text-zinc-600"
                )}
              >
                {icons[item.icon]}
                {item.label}
              </Link>
            );
          })}
        </div>
      </nav>
    </div>
  );
}
